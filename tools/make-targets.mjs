/**
 * make-targets.mjs — generate the printable capture mats.
 *
 * ---------------------------------------------------------------------------
 * ONE SOURCE, BOTH PAGE SIZES.
 *
 * The Letter variant was first produced by search-and-replacing coordinates in
 * the A4 file. It rendered a scale bar 183.72 mm long instead of 180 — because
 * the substitutions moved the end ticks (`x1`) without moving the blocks (`x`),
 * so the geometry silently came apart. A target whose printed length is wrong
 * is worse than no target: every measurement taken from the resulting model is
 * wrong by that factor, and nothing downstream can detect it.
 *
 * So both sizes are generated from the same geometry with the page as a
 * parameter, and `tools/check-targets.mjs` renders them and measures the bar.
 *
 * THE BAR'S BLACK EXTENT IS EXACTLY THE NOMINAL LENGTH.
 *
 * The first version drew end ticks with a 1.2 mm stroke centred on the end
 * coordinates, so the ink extended 0.6 mm past each end and the bar measured
 * 181.2 mm while claiming 180. Whoever laid a ruler along it would read the
 * ink, not the intended centre-line. The ticks are now filled rectangles that
 * sit inside the span, so what you see and what is nominal are the same thing.
 * ---------------------------------------------------------------------------
 */
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'assets');

const PAGES = [
  { id: 'a4', label: 'A4', w: 210, h: 297 },
  { id: 'letter', label: 'US LETTER', w: 215.9, h: 279.4 },
];

const BAR_MM = 180;       // nominal, and the exact black extent
const TICK_W = 0.7;       // tick thickness, drawn INSIDE the span
const BLOCK = 20;         // alternating block length

function svg({ label, w, h }) {
  const cx = w / 2;
  const x0 = (w - BAR_MM) / 2;          // bar starts here
  const x1 = x0 + BAR_MM;               // and ends here, exactly
  const barY = 52.5;
  const barH = 7;

  // Alternating blocks. The first starts at x0 and the last ends at x1, so the
  // ink spans exactly BAR_MM with no stroke to overshoot.
  const blocks = [];
  for (let i = 0; i * BLOCK * 2 < BAR_MM; i++) {
    const bx = x0 + i * BLOCK * 2;
    const bw = Math.min(BLOCK, x1 - bx);
    if (bw > 0) blocks.push(`  <rect x="${r(bx)}" y="${barY}" width="${r(bw)}" height="${barH}"/>`);
  }
  // A final block flush to the right end, so the ink truly reaches x1.
  const lastEnd = x0 + Math.floor((BAR_MM - BLOCK) / (BLOCK * 2)) * BLOCK * 2 + BLOCK;
  if (lastEnd < x1) blocks.push(`  <rect x="${r(x1 - BLOCK)}" y="${barY}" width="${BLOCK}" height="${barH}"/>`);

  const labels = [];
  for (let mm = 0; mm <= BAR_MM; mm += 40) {
    labels.push(`  <text x="${r(x0 + mm)}" y="66.5" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="3">${mm}</text>`);
  }

  // Colour patches, centred as a block.
  const patchW = 20, patchH = 14, patchN = 9;
  const px0 = cx - (patchW * patchN) / 2;
  const colours = ['#ffffff', '#c0c0c0', '#808080', '#404040', '#000000', '#c8322d', '#2d8a3e', '#2b5fa8', '#d8a422'];
  const patches = colours.map((c, i) =>
    `  <rect x="${r(px0 + i * patchW)}" y="85" width="${patchW}" height="${patchH}" fill="${c}" stroke="#000" stroke-width="0.3"/>`);
  const patchLabels = ['white', '75%', '50%', '25%', 'black'].map((t, i) =>
    `  <text x="${r(px0 + i * patchW + patchW / 2)}" y="103" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="2.4">${t}</text>`);

  // Object area: a 120 mm square, centred.
  const oW = 120;
  const ox = cx - oW / 2;
  const oy = 112;
  const oy2 = oy + oW;

  // Record block sits above the footer, whatever the page height.
  const recY = h - 51;
  const footY = h - 9;

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}mm" height="${h}mm" viewBox="0 0 ${w} ${h}">
<title>Turnstone object capture mat (${label})</title>
<desc>Print at 100% / Actual size, then MEASURE the scale bar and enter the measured value.</desc>

<!--
  TURNSTONE OBJECT CAPTURE MAT - ${label}

  GENERATED by tools/make-targets.mjs. Do not hand-edit: both page sizes come
  from the same geometry so they cannot drift apart, and tools/check-targets.mjs
  renders this file and measures the bar to confirm it is ${BAR_MM}.00 mm.

  Units are millimetres. The viewBox is ${w}x${h} and the page is declared
  ${w}mm x ${h}mm, so one user unit is exactly one millimetre.

  WHAT EACH PART IS FOR:

  SCALE BAR. Satisfies scale-reference, and gives ground sample distance as
  measured-length divided by pixels-spanned - which needs no focal length, no
  sensor size and no distance, the three things a phone browser reports least
  reliably. The black ink spans exactly ${BAR_MM} mm; the end ticks are drawn
  inside the span so that what you measure is what is nominal.

  FIDUCIALS round the perimeter. The object sits in the middle, so as the camera
  orbits some markers stay unoccluded. A single marker in one corner disappears
  behind the object for a third of the orbit. The four glyphs differ from each
  other because identical markers give the matcher ambiguous correspondences.

  COLOUR PATCHES. Condition assessment depends on colour being comparable across
  captures years apart. Without a reference the record carries whatever cast the
  room lighting had, and a later capture cannot distinguish deterioration from a
  different set of light bulbs.
-->

<rect width="${w}" height="${h}" fill="#ffffff"/>

<text x="${r(cx)}" y="16" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="6.5" font-weight="bold" letter-spacing="0.8">TURNSTONE OBJECT CAPTURE MAT</text>
<text x="${r(cx)}" y="22" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="3.2" fill="#555">ethical-tech-colab.github.io/turnstone</text>

<rect x="${r(cx - 85)}" y="26" width="170" height="13" fill="none" stroke="#000" stroke-width="0.5"/>
<text x="${r(cx)}" y="31.5" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="3.6" font-weight="bold">PRINT AT 100% / "ACTUAL SIZE" - NOT "FIT TO PAGE"</text>
<text x="${r(cx)}" y="36.5" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="3.2">Then measure the black bar below and enter what you actually measured.</text>

<g id="scale-bar" fill="#000">
${blocks.join('\n')}
  <rect x="${r(x0)}" y="50" width="${TICK_W}" height="12"/>
  <rect x="${r(x1 - TICK_W)}" y="50" width="${TICK_W}" height="12"/>
</g>
<rect x="${r(x0)}" y="${barY}" width="${BAR_MM}" height="${barH}" fill="none" stroke="#000" stroke-width="0.25"/>
${labels.join('\n')}
<text x="${r(cx)}" y="47" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="4" font-weight="bold">MEASURE THIS - the full black bar, end to end</text>
<text x="${r(cx)}" y="71.5" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="3.4">nominal ${BAR_MM}.0 mm</text>

<g id="colour">
  <text x="${r(px0)}" y="82" font-family="Helvetica,Arial,sans-serif" font-size="3.4" font-weight="bold">COLOUR REFERENCE</text>
  <text x="${r(px0 + 55)}" y="82" font-family="Helvetica,Arial,sans-serif" font-size="2.8" fill="#555">so a capture years from now is comparable to this one</text>
${patches.join('\n')}
${patchLabels.join('\n')}
</g>

<g id="object-area">
  <rect x="${r(ox)}" y="${oy}" width="${oW}" height="${oW}" fill="none" stroke="#999" stroke-width="0.4" stroke-dasharray="3 2"/>
  <text x="${r(cx)}" y="${oy + 58}" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="5" fill="#aaa" letter-spacing="1.5">PLACE OBJECT HERE</text>
  <text x="${r(cx)}" y="${oy + 65}" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="3" fill="#aaa">keep it inside the dashed square</text>

  <g fill="#000">
    <rect x="${r(cx - 6)}" y="${oy + 3}" width="12" height="12"/>
    <rect x="${r(cx - 3)}" y="${oy + 6}" width="6" height="6" fill="#fff"/>
    <circle cx="${r(cx)}" cy="${oy2 - 11}" r="6"/>
    <circle cx="${r(cx)}" cy="${oy2 - 11}" r="3" fill="#fff"/>
    <path d="M ${r(ox + 6)} ${oy + 60} l 12 -6 l 0 12 z"/>
    <path d="M ${r(ox + oW - 6)} ${oy + 60} l 6 -6 l 6 6 l -6 6 z"/>
  </g>

  <g stroke="#000" stroke-width="0.8" fill="none">
    <path d="M ${r(ox)} ${oy + 8} L ${r(ox)} ${oy} L ${r(ox + 8)} ${oy}"/>
    <path d="M ${r(ox + oW - 8)} ${oy} L ${r(ox + oW)} ${oy} L ${r(ox + oW)} ${oy + 8}"/>
    <path d="M ${r(ox + oW)} ${oy2 - 8} L ${r(ox + oW)} ${oy2} L ${r(ox + oW - 8)} ${oy2}"/>
    <path d="M ${r(ox + 8)} ${oy2} L ${r(ox)} ${oy2} L ${r(ox)} ${oy2 - 8}"/>
  </g>
  <text x="${r(cx)}" y="${oy2 + 6}" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="2.8" fill="#777">corner to corner: ${oW}.0 mm nominal</text>
</g>

<g id="record">
  <rect x="${r(cx - 90)}" y="${recY}" width="180" height="34" fill="none" stroke="#000" stroke-width="0.5"/>
  <text x="${r(cx - 85)}" y="${recY + 7}" font-family="Helvetica,Arial,sans-serif" font-size="3.4" font-weight="bold">WRITE THIS ON THE CARD ONCE, THEN REUSE IT</text>

  <text x="${r(cx - 85)}" y="${recY + 16}" font-family="Helvetica,Arial,sans-serif" font-size="3">MEASURED BAR LENGTH</text>
  <line x1="${r(cx - 33)}" y1="${recY + 17}" x2="${r(cx)}" y2="${recY + 17}" stroke="#000" stroke-width="0.3"/>
  <text x="${r(cx + 2)}" y="${recY + 16}" font-family="Helvetica,Arial,sans-serif" font-size="3">mm</text>

  <text x="${r(cx + 15)}" y="${recY + 16}" font-family="Helvetica,Arial,sans-serif" font-size="3">CARD ID</text>
  <line x1="${r(cx + 34)}" y1="${recY + 17}" x2="${r(cx + 85)}" y2="${recY + 17}" stroke="#000" stroke-width="0.3"/>

  <text x="${r(cx - 85)}" y="${recY + 25}" font-family="Helvetica,Arial,sans-serif" font-size="3">DATE MEASURED</text>
  <line x1="${r(cx - 45)}" y1="${recY + 26}" x2="${r(cx)}" y2="${recY + 26}" stroke="#000" stroke-width="0.3"/>

  <text x="${r(cx + 15)}" y="${recY + 25}" font-family="Helvetica,Arial,sans-serif" font-size="3">MEASURED BY</text>
  <line x1="${r(cx + 47)}" y1="${recY + 26}" x2="${r(cx + 85)}" y2="${recY + 26}" stroke="#000" stroke-width="0.3"/>

  <text x="${r(cx - 85)}" y="${recY + 32}" font-family="Helvetica,Arial,sans-serif" font-size="2.6" fill="#555">Enter the MEASURED length in the app, not the nominal one. A page scaled to 96% makes every measurement 4% wrong.</text>
</g>

<text x="${r(cx)}" y="${footY - 5}" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="2.6" fill="#777">Keep the mat flat and unfolded. A creased mat is no longer a straight line of known length.</text>
<text x="${r(cx)}" y="${footY}" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="2.4" fill="#999">CC0 - copy, print and modify freely</text>

</svg>
`;
}

const r = (n) => Number(n.toFixed(3)).toString();

for (const page of PAGES) {
  const path = join(OUT, `target-${page.id}.svg`);
  writeFileSync(path, svg(page), 'utf8');
  console.log(`  wrote target-${page.id}.svg  (${page.w} x ${page.h} mm, bar ${BAR_MM}.00 mm)`);
}
